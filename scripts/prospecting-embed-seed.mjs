// Copies data/prospecting/*.csv into a TypeScript module so the ontology
// import works everywhere (demo, CLI, Vercel functions) without relying on
// file tracing. The CSVs stay the source of truth; a unit test fails if the
// embedded copy drifts. Run after editing either CSV:
//   node scripts/prospecting-embed-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const files = {
  NICHES_CSV: "data/prospecting/service_business_niches.csv",
  BUYER_TYPES_CSV: "data/prospecting/icp_customer_buyer_types.csv",
};
let out = "/* Generated by scripts/prospecting-embed-seed.mjs — do not edit by hand. */\n";
for (const [name, path] of Object.entries(files)) {
  out += `\nexport const ${name}_FILE = ${JSON.stringify(path.split("/").pop())};\n`;
  out += `export const ${name} = ${JSON.stringify(readFileSync(path, "utf8"))};\n`;
}
writeFileSync("src/server/prospecting/ontology/seed-data.ts", out);
console.log("✔ embedded", Object.values(files).join(", "));
